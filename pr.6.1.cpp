// Лабораторна робота № 6.1 (варіант 30).
// Масив a із 25 цілих елементів, значення з діапазону [-20; 30].
// Критерій: всі додатні парні елементи.
// Дії: порахувати кількість, суму, замінити такі елементи нулями.
// Виконано двома способами: ітераційним та рекурсивним.
// Обидва масиви заповнюються однаковою послідовністю випадкових чисел
// (однакове початкове значення srand), тому результати можна порівняти.
#include <iostream>
#include <cstdlib>
#include <ctime>
#include "MyMath.h"
using namespace std;

int main()
{
    const int n = 25;          // кількість елементів
    const int Low = -20;       // нижня межа діапазону
    const int High = 30;       // верхня межа діапазону
    const unsigned seed = (unsigned)time(NULL);

    int a[n];                  // масив для ітераційного способу
    int b[n];                  // масив для рекурсивного способу

    // ---------- Спосіб 1: ітераційний ----------
    cout << "===== Ітераційний спосіб =====" << endl;
    srand(seed);
    CreateIter(a, n, Low, High);
    cout << "Початковий масив:" << endl;
    PrintIter(a, n);

    cout << "Кількість: " << CountIter(a, n) << endl;
    cout << "Сума:      " << SumIter(a, n) << endl;

    ZeroIter(a, n);
    cout << "Модифікований масив:" << endl;
    PrintIter(a, n);

    // ---------- Спосіб 2: рекурсивний ----------
    cout << endl << "===== Рекурсивний спосіб =====" << endl;
    srand(seed);               // той самий початок послідовності -> той самий масив
    CreateRec(b, n, Low, High, 0);
    cout << "Початковий масив:" << endl;
    PrintRec(b, n, 0);

    cout << "Кількість: " << CountRec(b, n, 0) << endl;
    cout << "Сума:      " << SumRec(b, n, 0) << endl;

    ZeroRec(b, n, 0);
    cout << "Модифікований масив:" << endl;
    PrintRec(b, n, 0);

    return 0;
}
