// Лабораторна робота № 6.4 (варіант 30). Рекурсивний спосіб.
// Динамічний масив із n цілих елементів (n вводиться з клавіатури).
// 1.1. Мінімальний за модулем елемент.
// 1.2. Сума модулів елементів після першого нульового елемента.
// 2.   Перетворення: у першій половині – елементи з парних позицій,
//      у другій – елементи з непарних позицій; відносний порядок зберігається.
//      Позиції рахуємо з 1 (парні позиції 2,4,6... = індекси 1,3,5...).
#include <iostream>
#include <cstdlib>
#include <ctime>
#include "MyMath.h"
using namespace std;

int main()
{
    srand((unsigned)time(NULL));

    int n;
    cout << "n = ";
    cin >> n;
    if (n <= 0)
    {
        cout << "n має бути додатним" << endl;
        return 1;
    }

    const int Low = -10;
    const int High = 10;

    int* a = new int[n];                     // динамічний масив

    Create(a, n, Low, High, 0);
    cout << "Початковий масив:" << endl;
    Print(a, n, 0);

    // 1.1
    cout << "1.1. Мінімальний за модулем елемент: " << MinAbs(a, n, 0) << endl;

    // 1.2
    int z = FindFirstZero(a, n, 0);
    if (z == -1)
        cout << "1.2. Нульових елементів немає" << endl;
    else
        cout << "1.2. Сума модулів після першого нуля: " << SumAbs(a, n, z + 1) << endl;

    // 2
    Rearrange(a, n);
    cout << "2. Перетворений масив:" << endl;
    Print(a, n, 0);

    delete[] a;                              // звільняємо пам'ять
    return 0;
}
